// Bundles rooms.json + works.json into assets/data/site-data.js (so the site also works when
// index.html is opened straight from disk, where fetch() of local JSON is blocked), and writes the
// plain "all works" list between the WORKS markers in index.html for visitors without JavaScript.
//   node tools/build-site-data.js
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const read = p => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));

const { works } = read('assets/data/works.json');
const roomsData = read('assets/data/rooms.json');

// Optional media base (e.g. a CDN for full.mp4). Empty = same folder as the site.
const MEDIA_BASE = process.env.MEDIA_BASE || '';
for (const w of works) if (MEDIA_BASE) w.full = MEDIA_BASE.replace(/\/$/, '') + '/' + w.full;

const CATS = {
  studio: 'צילומי אווירה ומאחורי הקלעים',
  business: 'וידאו לעסקים',
  events: 'אירועים ומוזיקה',
  ai: 'הפקות AI',
};
const site = { cats: CATS, works, ...roomsData };
fs.writeFileSync(path.join(ROOT, 'assets/data/site-data.js'),
  '/* generated by tools/build-site-data.js — edit works-src.tsv / rooms, not this file */\n' +
  'window.SITE = ' + JSON.stringify(site) + ';\n');

const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const list = Object.entries(CATS).map(([cat, label]) => {
  const items = works.filter(w => w.category === cat || (cat === 'studio' && w.category === 'showreel'))
    .map(w => `<li><a href="${esc(w.full)}">${esc(w.title)}</a> · ${esc(w.client)}${w.pitch ? ` · ${esc(w.pitch)}` : ''}</li>`).join('\n          ');
  return `        <h4>${esc(label)}</h4>\n        <ul>\n          ${items}\n        </ul>`;
}).join('\n');
const block = `<!--WORKS:START-->\n      <noscript>\n      <section class="block nojs-works" aria-labelledby="nojs-title">\n        <h3 id="nojs-title">כל העבודות</h3>\n${list}\n      </section>\n      </noscript>\n      <!--WORKS:END-->`;

const idx = path.join(ROOT, 'index.html');
const html = fs.readFileSync(idx, 'utf8').replace(/<!--WORKS:START-->[\s\S]*?<!--WORKS:END-->/, block);
fs.writeFileSync(idx, html);
console.log('site-data.js:', works.length, 'works,', roomsData.rooms.length, 'rooms; noscript list updated');
